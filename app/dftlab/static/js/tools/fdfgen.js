// SIESTA input (.fdf) and cluster job script generators. Pure functions: params in, text out.
// The geometry blocks come from crystal/formats.js; everything else is assembled here.
import { writeFDF, kgridFromSpacing } from '../crystal/formats.js';
import { symbolOf } from '../crystal/elements.js';

export const XC = {
  'LDA':     { functional:'LDA', authors:'CA',    note:'Ceperley–Alder (Perdew–Zunger)', pseudo:'lda' },
  'PBE':     { functional:'GGA', authors:'PBE',   note:'Perdew–Burke–Ernzerhof', pseudo:'pbe' },
  'PBEsol':  { functional:'GGA', authors:'PBEsol',note:'PBE para sólidos', pseudo:'pbe' },
  'revPBE':  { functional:'GGA', authors:'revPBE',note:'Zhang–Yang', pseudo:'pbe' },
  'vdW-DF':  { functional:'VDW', authors:'DRSLL', note:'Dion et al. 2004 (vdW-DF1)', pseudo:'pbe' },
  'VV10':    { functional:'VDW', authors:'VV',    note:'Vydrov–Van Voorhis 2010', pseudo:'pbe' },
};
export const BASIS = ['SZ','SZP','DZ','DZP','TZP'];

export const DEFAULTS = {
  label:'siesta', name:'', xc:'PBE', basis:'DZP', energyShift:20, mesh:300,
  kmode:'spacing', kspacing:0.2, kgrid:[4,4,4], kshift:0.5,
  spin:'none', occ:'FD', temp:300,
  mixer:'Pulay', weight:0.25, history:6, mix:'Hamiltonian', maxit:200, dmTol:1e-4, hTol:1e-3,
  run:'single', maxForce:0.02, cgSteps:200, varCell:false, maxStress:0.1,
  bands:true, pdos:true, pdosRange:[-20,10], pdosSigma:0.1, mulliken:true, rho:false, optical:false, coop:false, saveHS:false,
  lua:false, coordinates:'Fractional',
};

const line = (k, v) => `${k.padEnd(28)} ${v}`;

/** Build a complete SIESTA input. `cell` is a DFT Lab cell; `kpath` an optional kpath.getPathOrigCell result. */
export function siestaInput(cell, p0 = {}, kpath = null) {
  const p = { ...DEFAULTS, ...p0 };
  const xc = XC[p.xc] || XC.PBE;
  const species = [...new Set(cell.numbers)];
  const out = [];
  out.push(`# ${'='.repeat(70)}`);
  out.push(`# SIESTA input generated by DFT Lab (${new Date().toISOString().slice(0,10)})`);
  out.push(`# Pseudopotentials expected next to this file: ${species.map(z=>symbolOf(z)+'.psml').join(', ')}`);
  out.push(`#   (or .psf; ${xc.pseudo.toUpperCase()} pseudos to match XC.functional ${p.xc})`);
  out.push(`# ${'='.repeat(70)}`, '');
  out.push(line('SystemName', p.name || p.label), '');
  out.push('# ---- Geometry ----');
  out.push(writeFDF(cell, { systemLabel: p.label, coordinates: p.coordinates }).trimEnd(), '');

  out.push('# ---- Hamiltonian ----');
  out.push(line('XC.functional', xc.functional), line('XC.authors', xc.authors) + `    # ${xc.note}`);
  if (p.spin !== 'none') out.push(line('Spin', p.spin));
  out.push(line('PAO.BasisSize', p.basis), line('PAO.EnergyShift', `${p.energyShift} meV`));
  out.push(line('MeshCutoff', `${p.mesh} Ry`), '');

  out.push('# ---- Brillouin zone sampling ----');
  const n = p.kmode === 'grid' ? p.kgrid : kgridFromSpacing(cell, p.kspacing);
  out.push(`# ${n.join('x')} Monkhorst-Pack${p.kmode==='grid'?'':` from k-spacing ${p.kspacing} 1/Ang (2*pi included)`}`);
  out.push('%block kgrid_Monkhorst_Pack');
  for (let i = 0; i < 3; i++) { const r=[0,0,0]; r[i]=n[i]; out.push(`  ${r.map(x=>String(x).padStart(4)).join(' ')}   ${(+p.kshift).toFixed(1)}`); }
  out.push('%endblock kgrid_Monkhorst_Pack', '');

  out.push('# ---- Occupations ----');
  out.push(line('OccupationFunction', p.occ === 'MP' ? 'MP' : 'FD'));
  if (p.occ === 'MP') out.push(line('OccupationMPOrder', 1));
  out.push(line('ElectronicTemperature', `${p.temp} K`), '');

  out.push('# ---- Self-consistency ----');
  out.push(line('SCF.Mix', p.mix), line('SCF.Mixer.Method', p.mixer), line('SCF.Mixer.Weight', p.weight));
  if (p.mixer !== 'Linear') out.push(line('SCF.Mixer.History', p.history));
  out.push(line('MaxSCFIterations', p.maxit), line('SCF.DM.Tolerance', p.dmTol), line('SCF.H.Tolerance', `${p.hTol} eV`));
  out.push(line('DM.UseSaveDM', 'T'), '');

  if (p.run !== 'single') {
    out.push('# ---- Geometry optimization ----');
    out.push(line('MD.TypeOfRun', 'CG'), line('MD.Steps', p.cgSteps), line('MD.MaxForceTol', `${p.maxForce} eV/Ang`));
    if (p.varCell) out.push(line('MD.VariableCell', 'T'), line('MD.MaxStressTol', `${p.maxStress} GPa`));
    out.push(line('MD.UseSaveXV', 'T'), line('WriteCoorXmol', 'T'), '');
  }

  out.push('# ---- Output ----');
  if (p.mulliken) out.push(line('WriteMullikenPop', 1));
  out.push(line('WriteEigenvalues', 'T'));
  if (p.rho) out.push(line('SaveRho', 'T'), line('SaveDeltaRho', 'T'));
  if (p.saveHS) out.push(line('TS.HS.Save', 'T') + '    # <label>.TSHS for sisl', line('CDF.Save', 'T'));
  if (p.coop) out.push(line('COOP.Write', 'T'));
  if (p.pdos) {
    out.push('%block ProjectedDensityOfStates', `  ${p.pdosRange[0].toFixed(2)}  ${p.pdosRange[1].toFixed(2)}  ${p.pdosSigma}  2000  eV`, '%endblock ProjectedDensityOfStates');
    out.push('%block PDOS.kgrid_Monkhorst_Pack');
    for (let i = 0; i < 3; i++) { const r=[0,0,0]; r[i]=Math.max(1,2*n[i]); out.push(`  ${r.map(x=>String(x).padStart(4)).join(' ')}   ${(+p.kshift).toFixed(1)}`); }
    out.push('%endblock PDOS.kgrid_Monkhorst_Pack');
  }
  if (p.optical) {
    out.push(line('OpticalCalculation', 'T'), line('Optical.Energy.Minimum', '0 Ry'), line('Optical.Energy.Maximum', '2 Ry'),
      line('Optical.Broaden', '0.01 Ry'), line('Optical.PolarizationType', 'polycrystal'));
    out.push('%block Optical.Mesh', `  ${n.map(x=>2*x).join(' ')}`, '%endblock Optical.Mesh');
  }
  if (p.bands && kpath) {
    out.push('');
    out.push('# ---- Band structure (seekpath / HPKOT path) ----');
    out.push(bandLinesFor(cell, kpath).trimEnd());
  }
  if (p.lua) out.push('', line('Lua.Script', 'dftlab_scf_hook.lua') + '    # writes live.jsonl every SCF step');
  return out.join('\n') + '\n';
}

// BandLines for the user's own cell, from kpath.getPathOrigCell (special points already expressed
// in the reciprocal basis of that cell), written with BandLinesScale ReciprocalLatticeVectors.
export function bandLinesFor(cell, res, ref = 0.025) {
  const A = cell.lattice, V = A[0][0]*(A[1][1]*A[2][2]-A[1][2]*A[2][1]) - A[0][1]*(A[1][0]*A[2][2]-A[1][2]*A[2][0]) + A[0][2]*(A[1][0]*A[2][1]-A[1][1]*A[2][0]);
  const cr = (u, v) => [u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0]];
  const B = [cr(A[1],A[2]), cr(A[2],A[0]), cr(A[0],A[1])].map(v => v.map(x => 2*Math.PI*x/V));
  const cart = k => [0,1,2].map(j => k[0]*B[0][j] + k[1]*B[1][j] + k[2]*B[2][j]);
  const fmt = x => (Math.abs(x) < 5e-9 ? ' 0.00000000' : (x >= 0 ? ' ' : '') + x.toFixed(8));
  const L = [`# k-path: HPKOT/seekpath, extended Bravais lattice ${res.bravais_lattice_extended}, space group ${res.spacegroup_number}`,
    '# coordinates in the reciprocal basis of the cell above',
    '# a line with 1 point after a jump (e.g. U|K) is joined by SIESTA with a single step', 'BandLinesScale  ReciprocalLatticeVectors', '%block BandLines'];
  let last = null;
  for (const [a, b] of res.path) {
    const fa = res.point_coords[a], fb = res.point_coords[b], ka = cart(fa), kb = cart(fb);
    if (last !== a) L.push(`  ${'1'.padStart(4)}  ${fa.map(fmt).join(' ')}   ${a.replace(/^GAMMA/, '\\Gamma')}`);
    const len = Math.hypot(kb[0]-ka[0], kb[1]-ka[1], kb[2]-ka[2]);
    L.push(`  ${String(Math.max(1, Math.round(len / ref))).padStart(4)}  ${fb.map(fmt).join(' ')}   ${b.replace(/^GAMMA/, '\\Gamma')}`);
    last = b;
  }
  L.push('%endblock BandLines');
  return L.join('\n') + '\n';
}

export const SCHED_DEFAULTS = { sched:'slurm', job:'siesta', nodes:1, ntasks:16, omp:1, time:'24:00:00', mem:'', partition:'', account:'', queue:'',
  modules:'module load siesta', siesta:'siesta', launcher:'auto', scratch:false };

/** Job script for SLURM, PBS/Torque, SGE or a plain workstation run. */
export function jobScript(label, species, q0 = {}) {
  const q = { ...SCHED_DEFAULTS, ...q0 };
  const np = q.nodes * q.ntasks;
  const launch = q.launcher === 'auto' ? (q.sched === 'slurm' ? 'srun' : q.sched === 'local' ? (np > 1 ? `mpirun -np ${np}` : '') : `mpirun -np ${np}`) : q.launcher;
  const H = ['#!/bin/bash'];
  if (q.sched === 'slurm') {
    H.push(`#SBATCH --job-name=${q.job}`, `#SBATCH --nodes=${q.nodes}`, `#SBATCH --ntasks-per-node=${q.ntasks}`, `#SBATCH --cpus-per-task=${q.omp}`, `#SBATCH --time=${q.time}`);
    if (q.mem) H.push(`#SBATCH --mem=${q.mem}`);
    if (q.partition) H.push(`#SBATCH --partition=${q.partition}`);
    if (q.account) H.push(`#SBATCH --account=${q.account}`);
    H.push(`#SBATCH --output=${label}.%j.log`);
  } else if (q.sched === 'pbs') {
    H.push(`#PBS -N ${q.job}`, `#PBS -l nodes=${q.nodes}:ppn=${q.ntasks * q.omp}`, `#PBS -l walltime=${q.time}`);
    if (q.mem) H.push(`#PBS -l mem=${q.mem}`);
    if (q.queue || q.partition) H.push(`#PBS -q ${q.queue || q.partition}`);
    if (q.account) H.push(`#PBS -A ${q.account}`);
    H.push('#PBS -j oe', 'cd "$PBS_O_WORKDIR"');
  } else if (q.sched === 'sge') {
    H.push(`#$ -N ${q.job}`, `#$ -pe mpi ${np}`, `#$ -l h_rt=${q.time}`, '#$ -cwd', '#$ -j y');
    if (q.queue || q.partition) H.push(`#$ -q ${q.queue || q.partition}`);
  }
  H.push('', '# Generated by DFT Lab. Check module names and paths for your machine.', 'set -euo pipefail', '');
  if (q.modules.trim()) H.push(q.modules.trim(), '');
  H.push(`export OMP_NUM_THREADS=${q.omp}`, '');
  H.push(`for f in ${species.map(z => symbolOf(z)).join(' ')}; do`,
    '  ls "$f".psml >/dev/null 2>&1 || ls "$f".psf >/dev/null 2>&1 || { echo "Missing pseudopotential for $f"; exit 1; }', 'done', '');
  if (q.scratch) {
    const sc = q.sched === 'slurm' ? '${SLURM_TMPDIR:-/tmp}/$SLURM_JOB_ID' : q.sched === 'pbs' ? '${TMPDIR:-/tmp}/$PBS_JOBID' : '${TMPDIR:-/tmp}/siesta_$$';
    H.push(`WORK=${sc}`, 'mkdir -p "$WORK"', `cp ${label}.fdf *.psml *.psf *.lua "$WORK"/ 2>/dev/null || true`, 'cd "$WORK"', '');
  }
  H.push(`${launch ? launch + ' ' : ''}${q.siesta} < ${label}.fdf > ${label}.out`);
  if (q.scratch) H.push('', 'cp -r "$WORK"/* "$OLDPWD"/ && cd "$OLDPWD"');
  H.push('', `grep -q "Job completed" ${label}.out && echo "SIESTA finished OK" || echo "SIESTA did not finish, see ${label}.out"`);
  return H.join('\n') + '\n';
}
